from datetime import date

import streamlit as st

from finsense import anomaly, data, forecast, health, personality, theme
from finsense.data import inr, pct
from finsense.theme import esc
from finsense.views.common import require_data


def build_html_report(df):
    stats = data.headline_stats(df)
    monthly = data.monthly_summary(df)
    score = health.compute_health(monthly)
    persona = personality.archetype(personality.traits(df))
    scanned = anomaly.scan(df)
    flagged = (
        anomaly.flag(scanned, 3).query("Flagged").sort_values("Radar_Score", ascending=False).head(10)
        if "Radar_Score" in scanned and scanned["Radar_Score"].notna().any() else None
    )
    sim = forecast.simulate(monthly, 12) if len(monthly) >= 3 else None

    comp_rows = "".join(
        f"<tr><td>{esc(c['name'])}</td><td class=n>{c['points']:.0f} / {c['max']}</td>"
        f"<td>{esc(c['value'])}</td><td>{esc(c['tip'])}</td></tr>"
        for c in score["components"]
    )
    cat_rows = "".join(
        f"<tr><td>{esc(cat)}</td><td class=n>{inr(v)}</td>"
        f"<td class=n>{v / stats['expense'] * 100:.1f}%</td></tr>"
        for cat, v in stats["by_category"].items()
    )
    flag_rows = "" if flagged is None else "".join(
        f"<tr><td>{r.Date:%d %b %Y}</td><td>{esc(r.Category)}</td><td class=n>{inr(r.Amount)}</td>"
        f"<td>{esc('; '.join(r.Reasons))}</td></tr>"
        for r in flagged.itertuples()
    )
    outlook = "" if sim is None else (
        f"<p>Likely net position in 12 months: <b>{inr(sim['balance']['P50'].iloc[-1], sign=True)}</b> "
        f"(80% range {inr(sim['balance']['P10'].iloc[-1], sign=True)} to "
        f"{inr(sim['balance']['P90'].iloc[-1], sign=True)}).</p>"
    )

    return f"""<!doctype html><html><head><meta charset="utf-8">
<title>FinSense AI Report</title>
<style>
body{{font-family:system-ui,sans-serif;max-width:860px;margin:40px auto;padding:0 20px;color:#1a2233}}
h1{{margin-bottom:0}} .sub{{color:#667;margin-top:4px}}
.cards{{display:grid;grid-template-columns:repeat(4,1fr);gap:12px;margin:24px 0}}
.card{{border:1px solid #dde;border-radius:10px;padding:12px}} .card b{{display:block;font-size:1.3rem}}
table{{width:100%;border-collapse:collapse;margin:8px 0 24px}} td,th{{border-bottom:1px solid #eee;padding:6px;text-align:left;font-size:.9rem}}
.n{{text-align:right;font-variant-numeric:tabular-nums}} h2{{margin-top:32px}}
</style></head><body>
<h1>FinSense AI — Financial Report</h1>
<p class=sub>{stats['start']:%d %b %Y} – {stats['end']:%d %b %Y} · {stats['transactions']:,} transactions · generated {date.today():%d %b %Y}</p>
<div class=cards>
<div class=card>Money in<b>{inr(stats['income'])}</b></div>
<div class=card>Money out<b>{inr(stats['expense'])}</b></div>
<div class=card>Net<b>{inr(stats['savings'], sign=True)}</b></div>
<div class=card>Health score<b>{score['score']}/100</b>{esc(score['grade'])}</div>
</div>
<h2>Health score breakdown</h2>
<table><tr><th>Component</th><th class=n>Points</th><th>Measured</th><th>How to improve</th></tr>{comp_rows}</table>
<h2>Money personality</h2>
<p><b>{esc(persona['name'])}</b> — {esc(persona['line'])}</p>
<h2>Spending by category</h2>
<table><tr><th>Category</th><th class=n>Total</th><th class=n>Share</th></tr>{cat_rows}</table>
<h2>Most unusual transactions</h2>
<table><tr><th>Date</th><th>Category</th><th class=n>Amount</th><th>Why flagged</th></tr>{flag_rows}</table>
<h2>12-month outlook</h2>{outlook}
<p class=sub>Savings rate {pct(stats['savings_rate'])} · Generated by FinSense AI. Not financial advice.</p>
</body></html>"""


def render():
    df = require_data()
    theme.hero("Report", "Take it with you",
               "A one-page summary of everything FinSense found, ready to open in any browser or print to PDF.")

    report = build_html_report(df)
    monthly = data.monthly_summary(df)

    c1, c2 = st.columns(2)
    with c1:
        st.download_button("Download full report (HTML)", report.encode("utf-8"),
                           "finsense_report.html", "text/html", type="primary", width="stretch")
    with c2:
        st.download_button("Download monthly summary (CSV)",
                           monthly.drop(columns="Period").to_csv(index=False).encode("utf-8"),
                           "finsense_monthly_summary.csv", "text/csv", width="stretch")

    st.markdown("#### Preview")
    # Every value from the user's file is HTML-escaped in build_html_report.
    st.iframe(report, height=900)
